
package com.mycompany.geriatrico1.modelo;


public class Enfermero {
    
    private String idEnfermera;
    private String idEmpleado;
    private String idHorario;
    private String numeroLicencia;
    private String nivelFormacion;
    private String especialidad;

    public Enfermero() {
    }

    public String getIdEnfermera() {
        return idEnfermera;
    }

    public void setIdEnfermera(String idEnfermera) {
        this.idEnfermera = idEnfermera;
    }

    public String getIdEmpleado() {
        return idEmpleado;
    }

    public void setIdEmpleado(String idEmpleado) {
        this.idEmpleado = idEmpleado;
    }

    public String getIdHorario() {
        return idHorario;
    }

    public void setIdHorario(String idHorario) {
        this.idHorario = idHorario;
    }

    public String getNumeroLicencia() {
        return numeroLicencia;
    }

    public void setNumeroLicencia(String numeroLicencia) {
        this.numeroLicencia = numeroLicencia;
    }

    public String getNivelFormacion() {
        return nivelFormacion;
    }

    public void setNivelFormacion(String nivelFormacion) {
        this.nivelFormacion = nivelFormacion;
    }

    public String getEspecialidad() {
        return especialidad;
    }

    public void setEspecialidad(String especialidad) {
        this.especialidad = especialidad;
    }
    
    
}
