
package com.mycompany.geriatrico1.modelo;


public class TipoTratamiento {
    private String idTipoTra;
    private String nombreDetTra;
    private String descripcionDetTra;
    private String objetivoDetTra;

    public TipoTratamiento() {
    }

    public String getIdTipoTra() {
        return idTipoTra;
    }

    public void setIdTipoTra(String idTipoTra) {
        this.idTipoTra = idTipoTra;
    }

    public String getNombreDetTra() {
        return nombreDetTra;
    }

    public void setNombreDetTra(String nombreDetTra) {
        this.nombreDetTra = nombreDetTra;
    }

    public String getDescripcionDetTra() {
        return descripcionDetTra;
    }

    public void setDescripcionDetTra(String descripcionDetTra) {
        this.descripcionDetTra = descripcionDetTra;
    }

    public String getObjetivoDetTra() {
        return objetivoDetTra;
    }

    public void setObjetivoDetTra(String objetivoDetTra) {
        this.objetivoDetTra = objetivoDetTra;
    }
    
}
